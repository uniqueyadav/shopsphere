CREATE TABLE IF NOT EXISTS products (
	id BIGINT NOT NULL AUTO_INCREMENT,
	seller_id BIGINT NOT NULL,
	category_id BIGINT NOT NULL,
	product_name VARCHAR(150) NOT NULL,
	slug VARCHAR(180) NOT NULL,
	description TEXT NULL,
	brand VARCHAR(100) NULL,
	sku VARCHAR(100) NOT NULL,
	price DECIMAL(12,2) NOT NULL,
	discount_price DECIMAL(12,2) NULL,
	stock_quantity INT NOT NULL,
	status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
	is_active BOOLEAN NOT NULL DEFAULT TRUE,
	reviewed_by BIGINT NULL,
	reviewed_at DATETIME(6) NULL,
	rejection_reason VARCHAR(1000) NULL,
	created_at DATETIME(6) NOT NULL,
	updated_at DATETIME(6) NOT NULL,
	CONSTRAINT pk_products PRIMARY KEY (id),
	CONSTRAINT uk_products_slug UNIQUE (slug),
	CONSTRAINT uk_products_sku UNIQUE (sku),
	CONSTRAINT fk_products_seller FOREIGN KEY (seller_id) REFERENCES sellers (id),
	CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
	CONSTRAINT fk_products_reviewed_by FOREIGN KEY (reviewed_by) REFERENCES shop_users (id),
	INDEX idx_products_marketplace (status, is_active, category_id),
	INDEX idx_products_seller (seller_id, created_at)
) ENGINE=InnoDB;
